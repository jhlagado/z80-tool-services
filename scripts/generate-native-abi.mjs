import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

import {
  NAMED_OBJECT_ABI_VERSION,
  NAMED_OBJECT_OPERATION,
  NAMED_OBJECT_REQUEST,
  NAMED_OBJECT_REQUEST_SIZE,
  NAMED_OBJECT_STATUS,
} from '../dist/abi.js';

const output = fileURLToPath(
  new URL('../native/z80-tool-services-v1.asmi', import.meta.url),
);
const entries = [
  ['ZT_ABI', NAMED_OBJECT_ABI_VERSION],
  ['ZT_RQLEN', NAMED_OBJECT_REQUEST_SIZE],
  ['ZT_FSIZE', NAMED_OBJECT_REQUEST.size],
  ['ZT_FABI', NAMED_OBJECT_REQUEST.abi],
  ['ZT_FOP', NAMED_OBJECT_REQUEST.operation],
  ['ZT_FFLG', NAMED_OBJECT_REQUEST.flags],
  ['ZT_FHND', NAMED_OBJECT_REQUEST.handle],
  ['ZT_FPTR', NAMED_OBJECT_REQUEST.pointer],
  ['ZT_FLEN', NAMED_OBJECT_REQUEST.length],
  ['ZT_FOFF', NAMED_OBJECT_REQUEST.offset],
  ['ZT_FRES', NAMED_OBJECT_REQUEST.result],
  ['ZT_OPEN', NAMED_OBJECT_OPERATION.openRead],
  ['ZT_BEGIN', NAMED_OBJECT_OPERATION.beginWrite],
  ['ZT_READ', NAMED_OBJECT_OPERATION.read],
  ['ZT_WRITE', NAMED_OBJECT_OPERATION.write],
  ['ZT_REW', NAMED_OBJECT_OPERATION.rewind],
  ['ZT_SEEK', NAMED_OBJECT_OPERATION.seek],
  ['ZT_CLOSE', NAMED_OBJECT_OPERATION.close],
  ['ZT_COM', NAMED_OBJECT_OPERATION.commit],
  ['ZT_ABORT', NAMED_OBJECT_OPERATION.abort],
  ['ZT_OK', NAMED_OBJECT_STATUS.success],
  ['ZT_INV', NAMED_OBJECT_STATUS.invalid],
  ['ZT_UNAV', NAMED_OBJECT_STATUS.unavailable],
  ['ZT_NF', NAMED_OBJECT_STATUS.notFound],
  ['ZT_CAP', NAMED_OBJECT_STATUS.capacity],
  ['ZT_ACC', NAMED_OBJECT_STATUS.access],
  ['ZT_STORE', NAMED_OBJECT_STATUS.storage],
  ['ZT_CONF', NAMED_OBJECT_STATUS.conflict],
  ['ZT_CAN', NAMED_OBJECT_STATUS.cancelled],
  ['ZT_UNSUP', NAMED_OBJECT_STATUS.unsupported],
];
if (entries.some(([name]) => name.length > 8)) {
  throw new Error("native ABI symbol exceeds Atom's eight-character limit");
}
if (new Set(entries.map(([name]) => name)).size !== entries.length) {
  throw new Error('native ABI symbols are not unique');
}
const text = [
  '; Generated by @jhlagado/z80-tool-services. Do not edit.',
  '; Named-object services ABI 1.',
  '',
  ...entries.map(([name, value]) => `${name} EQU ${value}`),
  '',
].join('\n');

if (process.argv.includes('--check')) {
  if (readFileSync(output, 'utf8') !== text) {
    throw new Error('native ABI include is stale; run npm run build');
  }
} else {
  writeFileSync(output, text);
}
