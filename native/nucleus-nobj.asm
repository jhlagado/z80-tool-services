; Nucleus NOBJ 0.1 profile for native/nobj-consumer.asm.
;
; Include this file with nobj-consumer.asm when ZN_PROF should accept the
; complete flat or banked Nucleus profile. IX addresses NN_SIZE bytes.
; Validation retains no bank or patch table: it rescans the immutable stored
; object for each bank and patch, keeping RAM use constant through 255 banks.

NB_FLAGS EQU 20
NB_BANKS EQU 21
NB_FILL EQU 22
NB_BASE EQU 23
NB_CAP EQU 25
NB_TEND EQU 27
NB_T64 EQU 29
NM_FLAGS EQU 30
NM_ENTRYBANK EQU 31
NM_ENTRY EQU 32
NM_WBASE EQU 34
NM_WCAP EQU 36
NM_WEND EQU 38
NM_W64 EQU 40
NM_VECTOR EQU 41
NM_VLEN EQU 43
NM_INIT EQU 45
NM_ILEN EQU 47
NM_IEND EQU 49
NM_BSSEND EQU 51
NM_BSS64 EQU 53
NM_STACK EQU 54
NM_LOADBANK EQU 56
NM_LOAD EQU 57
NM_LOADLEN EQU 59
NM_PARTS EQU 61
NN_PATCHES EQU 62
NN_BANKINDEX EQU 64
NN_USED EQU 65
NN_ROBASE EQU 67
NN_ROLEN EQU 69
NN_AGBASE EQU 71
NN_AGLEN EQU 73
NN_TMPBANK EQU 75
NN_TMPST EQU 76
NN_TMPEND EQU 78
NN_PREV EQU 80
NN_HIGH EQU 82
NN_PATCHINDEX EQU 84
NN_ORDINAL EQU 86
NN_PBANK EQU 88
